"""Writes the approved badge set (src/nfl-badges/badges.json) into the site: the NFL_BADGES block in site/assets/app.js.
Run after build_review.py whenever an emblem, typeface or colour changes:  python3 src/nfl-badges/apply.py"""
import json,re
B=json.load(open('src/nfl-badges/badges.json'))
slim={k:{'font':v['font'],'p':v['p'],'s':v['s'],'e':v['e'],'t':v['t'],'ring':v['ring'],'what':v['what'],'emblem':v['emblem']} for k,v in B.items()}
block="/* NFL_BADGES:BEGIN generated by src/nfl-badges/apply.py. Original emblems (city and fan identity), not team marks. */\nconst NFL_BADGES = "+json.dumps(slim,separators=(',',':'))+";\n/* NFL_BADGES:END */\n"
p='site/assets/app.js';a=open(p).read()
if 'NFL_BADGES:BEGIN' in a: a=re.sub(r"/\* NFL_BADGES:BEGIN.*?/\* NFL_BADGES:END \*/\n",lambda m:block,a,flags=re.S)
else:
    i=a.find('function nflBadge(');assert i>0;a=a[:i]+block+a[i:]
open(p,'w').write(a);print('badges written:',len(slim))
